-- SQL Table Definitions for StageDock Database Introspection
CREATE TABLE IF NOT EXISTS customers (
  id SERIAL PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(150) UNIQUE NOT NULL,
  company VARCHAR(120) NOT NULL,
  plan VARCHAR(40) DEFAULT 'ENTERPRISE',
  status VARCHAR(30) DEFAULT 'ACTIVE',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS orders (
  id SERIAL PRIMARY KEY,
  invoice_number VARCHAR(60) UNIQUE NOT NULL,
  customer_id INTEGER REFERENCES customers(id) ON DELETE CASCADE,
  product_name VARCHAR(150) NOT NULL,
  amount_inr INTEGER NOT NULL,
  payment_status VARCHAR(40) DEFAULT 'PAID',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS audit_logs (
  id SERIAL PRIMARY KEY,
  actor VARCHAR(100) NOT NULL,
  action VARCHAR(150) NOT NULL,
  endpoint VARCHAR(150) NOT NULL,
  risk_level VARCHAR(30) DEFAULT 'LOW',
  timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
